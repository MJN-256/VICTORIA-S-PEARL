const languageSelect = document.getElementById("language-select");

function getInitialLanguage() {
  try {
    const savedLanguage = window.localStorage.getItem("vicky-language");
    if (translations[savedLanguage]) return savedLanguage;
  } catch (error) {
    console.warn("Could not read the saved language preference.", error);
  }

  const preferences = navigator.languages.length ? navigator.languages : [navigator.language];
  return preferences
    .map(preference => preference.toLowerCase().split("-")[0])
    .find(language => translations[language]) || "en";
}

function setLanguage(language) {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    const value = dictionary[key];
    if (value === undefined) {
      console.error(`Missing "${key}" translation for "${language}".`);
      return;
    }

    const attribute = element.dataset.i18nAttr;
    if (attribute) {
      element.setAttribute(attribute, value);
    } else {
      element.textContent = value;
    }
  });
}

if (languageSelect) {
  const initialLanguage = getInitialLanguage();
  languageSelect.value = initialLanguage;
  setLanguage(initialLanguage);
  languageSelect.addEventListener("change", () => {
    setLanguage(languageSelect.value);
    try {
      window.localStorage.setItem("vicky-language", languageSelect.value);
    } catch (error) {
      console.warn("Could not save the language preference.", error);
    }
  });
}
